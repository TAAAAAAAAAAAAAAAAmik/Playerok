#!/bin/sh
# Сторож: держит бота запущенным, поднимая его после падения.
#
# Запускается через run_bot.sh, руками звать не нужно. Живёт в фоне и
# перезапускает бота, если тот вышел — по ошибке, по обрыву сети или по
# чему угодно ещё.
#
# Пауза перед перезапуском нужна: если бот падает сразу (нет ключей,
# сломан файл настроек), цикл без паузы выжрал бы процессор и залил
# журнал за минуты.

set -u

HERE=$(CD=$(dirname "$0"); cd "$CD" && pwd)
cd "$HERE"

PAUSE=5
# Если бот падает раз за разом, ждём дольше — до минуты. Чинить всё равно
# придётся руками, а частые попытки только мешают читать журнал.
MAX_PAUSE=60

while true; do
    START=$(date +%s)
    python3 -u item_bot.py
    CODE=$?
    LIVED=$(( $(date +%s) - START ))

    if [ "$CODE" = "0" ]; then
        echo "$(date '+%Y-%m-%d %H:%M:%S') бот вышел сам, больше не поднимаю"
        break
    fi

    if [ "$LIVED" -gt 60 ]; then
        PAUSE=5
    elif [ "$PAUSE" -lt "$MAX_PAUSE" ]; then
        PAUSE=$(( PAUSE * 2 ))
    fi

    echo "$(date '+%Y-%m-%d %H:%M:%S') бот упал (код $CODE, прожил ${LIVED}с), поднимаю через ${PAUSE}с"
    sleep "$PAUSE"
done
