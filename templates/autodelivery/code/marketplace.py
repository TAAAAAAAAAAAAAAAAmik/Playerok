# вопросы найдены и записаны в докстринге модуля playerok.py — там же
# указано, откуда взят каждый.
#
# Один пункт остаётся непроверенным по существу: какие статусы означают
# «оплачено». Ответ взят из исходников неофициальной библиотеки, а не с
# живого заказа, и именно в нём ошибка отдаёт коды бесплатно. Проверять
# его надо на своём тестовом заказе — см. docs/05_CHECKLIST.md.
