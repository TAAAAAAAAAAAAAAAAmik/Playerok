"""Порт маркетплейса — единственное место, которое пишется под новую площадку.

Движок выдачи (`delivery.py`) не знает ни про Юмаркет, ни про PlayerOK. Он
умеет только одно: «пришёл оплаченный заказ — купи код и отдай покупателю».
Всё, что зависит от площадки, спрятано за этим интерфейсом.

Перенос на другую площадку = написать один класс с пятью методами. Всё
остальное в шаблоне переносится как есть.

ВАЖНО. Реализация под PlayerOK ниже — **заглушка со списком того, что надо
выяснить**. Их API в этом шаблоне не проверялся: ни один метод, ни одно имя
поля, ни один статус. Догадки о чужом API стоили бы денег ровно там, где
здесь идёт покупка, поэтому вместо догадок — перечень вопросов и место, куда
вписать ответы.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Protocol, runtime_checkable


@dataclass
class Order:
    """Заказ так, как его видит движок. Площадка приводит свой формат к нему.

    Поля подобраны по тому, что выдаче правда нужно, а не по тому, что
    отдаёт площадка: лишнее поле в этом месте — это лишний повод, чтобы
    адаптеры разошлись.
    """
    id: str                    # номер заказа на площадке
    title: str                 # название товара — из него читается номинал
    status: str                # сырой статус площадки, как пришёл
    chat_id: str = ""          # куда писать покупателю; часто ≠ id заказа
    description: str = ""      # описание товара — из него читается регион
    buyer: str = ""            # ник покупателя, для журнала
    amount: float | None = None
    raw: dict = field(default_factory=dict)   # исходный ответ, для отладки


@runtime_checkable
class Marketplace(Protocol):
    """Что движок спрашивает у площадки. Пять методов, больше ничего."""

    name: str

    async def paid_orders(self) -> list[Order]:
        """Заказы, которые оплачены и ещё не обработаны нами.

        Возвращать надо **только оплаченные**. «Создан» деньгами не
        является: на таком заказе площадки обычно сами пишут «не выдавайте
        товар». Ошибка здесь = выдача бесплатно.
        """
        ...

    async def get_order(self, order_id: str) -> Order | None:
        """Один заказ по номеру. Нужен возобновлению оборванной выдачи:
        оно идёт из журнала, и карточки заказа под рукой у него нет."""
        ...

    async def send_message(self, chat_id: str, text: str) -> tuple[bool, str]:
        """Написать покупателю → (отправилось, причина по-русски).

        Причина нужна **всегда**, даже когда отправилось: журнал выдач
        показывает её продавцу. И причина должна быть переведённой: голый
        код ошибки на экране продавца — это «разбирайся сам».
        """
        ...

    def is_paid(self, status: str) -> bool:
        """Означает ли этот статус, что деньги у продавца.

        Отдельным методом, а не сравнением строк в движке: у каждой площадки
        свой словарь статусов, и он меняется.
        """
        ...

    def order_url(self, order_id: str) -> str:
        """Ссылка на заказ в кабинете — для уведомлений продавцу.
        Пустая строка — законный ответ, если такой ссылки нет."""
        ...


