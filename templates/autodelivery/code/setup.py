"""Подбор настроек выдачи по тому, что уже стоит на витрине.

Слово-опознаватель — самая тихая из настроек: ошибся, и бот либо проходит
мимо своих заказов, либо забирает чужие. Ровно это и случилось дважды.
Сначала слова не было вовсе, и выдача не узнавала объявления
«🥳ПРОМОКОДОМ🥳 АВТОВЫДАЧА😎». Потом слово поставили — «автовыдача», — и
оно совпало с объявлениями, которые продаются через геймпасс: другой
товар, другой способ выдачи, а код подарочной карты по нему покупать
нельзя.

Оба раза правильное слово было ВИДНО с витрины: оно есть у всех своих
объявлений и ни у одного чужого. Здесь это и считается.

Логика отдельно от бота нарочно: её можно прогнать на списке названий, а
не на живом кабинете.
"""
from __future__ import annotations

import re

# Из чего собираем слова названия. Эмодзи и знаки — не слова.
_WORD = re.compile(r"[A-Za-zА-Яа-яЁё0-9]{3,}")

# Слова, которые ничего не отличают: они есть у всех и у всех разные
# товары. Брать их опознавателем — значит забирать чужие заказы.
COMMON = frozenset((
    "код", "коды", "кода", "купить", "быстро", "дёшево", "дешево",
    "моментально", "мгновенно", "гарантия", "лучшая", "цена", "продажа",
    "акция", "новый", "топ", "хит", "автовыдача", "авто", "выдача",
    "gift", "card", "cards", "key", "buy", "fast", "instant", "global",
    "аккаунт", "аккаунта", "подарочная", "карта", "карты", "пополнение",
))

# Сколько слов предлагать продавцу на выбор.
SHOWN = 5


def words_of(name: str) -> set:
    """Слова названия, годные в опознаватели."""
    return {w.lower() for w in _WORD.findall(str(name or ""))
            if w.lower() not in COMMON and not w.isdigit()}


def keywords(ours: list, others: list, extra=(), prefer=()) -> list:
    """Какое слово годится в опознаватели. → [(слово, сколько своих)].

    Годное слово — то, что есть у СВОИХ объявлений и нет ни у одного
    чужого. Чужие важнее своих: пропустить свой заказ значит не выдать
    код и объясниться с покупателем, забрать чужой — купить не тот товар
    за свои деньги.

    Сначала идут слова, покрывающие больше своих объявлений.
    """
    ours = [str(n or "").lower() for n in ours]
    others = [str(n or "").lower() for n in others]
    candidates = set()

    for name in ours:
        candidates |= words_of(name)

    known = {str(w).lower() for w in extra if str(w).strip()}
    candidates |= known
    liked = {str(w).lower() for w in prefer}
    found = []

    for word in candidates:
        if any(word in name for name in others):
            continue

        mine = sum(1 for name in ours if word in name)

        # Ноль своих — обычно пустое слово. Но когда своих объявлений нет
        # ВОВСЕ, продавцу всё равно надо чем-то включить карту: он их
        # только собирается выставлять. Тогда годятся слова самой карты —
        # лишь бы не совпадали с чужими.
        if mine or (not ours and word in known):
            found.append((word, mine))

    # Больше своих — раньше. При равенстве сначала слова самой карты
    # («xbox»): они про товар, а не про его оформление, и переживут смену
    # региона или валюты в названии. Потом — короткие: их труднее
    # случайно потерять при правке названия.
    found.sort(key=lambda pair: (-pair[1], 0 if pair[0] in liked else 1,
                                 len(pair[0]), pair[0]))

    return found[:SHOWN]


def covered(names: list, word: str) -> list:
    """Какие названия попадут под это слово."""
    word = str(word or "").lower()

    return [n for n in names if word in str(n or "").lower()]


def region_of(names: list, region_in) -> str:
    """Самый частый регион в названиях. Пусто — если не прочитался.

    `region_in` передаётся снаружи, чтобы разбор регионов остался в одном
    месте: два разбора однажды разойдутся.
    """
    counts: dict = {}

    for name in names:
        code = region_in(str(name or ""))

        if code:
            counts[code] = counts.get(code, 0) + 1

    if not counts:
        return ""

    return sorted(counts.items(), key=lambda pair: (-pair[1], pair[0]))[0][0]
