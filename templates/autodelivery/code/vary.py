"""Чтобы копии объявления не были копиями до буквы.

Шаблон повторяет товар дословно, а площадки не любят одинаковые
объявления: десяток товаров с совпадающими полями выглядит накруткой,
даже когда это просто разные номиналы одного кода.

Поэтому свободные поля — «Комментарий», «Промокод» и подобные — при
повторе слегка меняются.

ЧТО ИМЕННО ПИШЕМ. Не случайный набор букв: поле может быть видно
покупателю, и «X7QF2» на странице товара выглядит поломкой магазина.
Пишем обычную фразу продавца — их несколько, и берётся каждый раз другая.

ОСОБО ПРО «ПРОМОКОД». Случайная строка там читается как код на скидку,
которого не существует: покупатель попробует его применить, не выйдет, и
это уже не разнообразие, а обман. Поэтому туда идёт обычная фраза.

И она ничего не утверждает о том, есть промокод или нет. Продавец может
торговать именно «через промокод» — так и называется его объявление, — а
бодрое «промокода нет» спорило бы с его же витриной. Фраза должна быть
верна в обоих случаях.
"""
from __future__ import annotations

import random

# Поля, которые разнообразим. Совпадение по вхождению: площадки называют
# их то «Комментарий», то «Комментарий к товару».
VARIED = ("комментарий", "промокод", "промо", "заметка", "comment", "note")

# Поля, куда нельзя писать ничего похожего на код.
PROMO = ("промокод", "промо", "promo")

# Фразы для комментария. Все — правда о товаре и ни одна ничего не
# обещает сверх того, что бот и так делает.
PHRASES = (
    "Выдача автоматическая, сразу после оплаты.",
    "Код приходит в чат заказа.",
    "Отвечаю на вопросы в чате.",
    "Код выдаётся сразу после подтверждения оплаты.",
    "Выдача без ожидания — бот отдаёт код в чат.",
    "Работаю без выходных, выдача автоматическая.",
    "Код придёт в чат заказа сразу после оплаты.",
    "Автовыдача: ждать ответа продавца не нужно.",
)

# Что пишем в поле промокода. Свой набор — чтобы два поля одного товара
# не получили одну фразу. Ни одна не выглядит кодом и ни одна не говорит,
# есть промокод или нет: это решает продавец, а не мы.
PROMO_PHRASES = (
    "Всё для активации придёт в чат заказа.",
    "Инструкция по активации — в чате после оплаты.",
    "Что делать дальше, бот напишет в чат заказа.",
    "Данные для активации приходят в чат сразу после оплаты.",
    "Подробности активации — в чате заказа.",
)


def varied(label: str) -> bool:
    """Это поле стоит разнообразить?"""
    low = str(label or "").lower()

    return any(word in low for word in VARIED)


def is_promo(label: str) -> bool:
    low = str(label or "").lower()

    return any(word in low for word in PROMO)


class Rotation:
    """Раздаёт фразы по кругу, не повторяя подряд.

    Простой `random.choice` на десяти объявлениях подряд легко выдаёт одну
    и ту же фразу дважды, а ровно этого мы и избегаем: две одинаковые
    копии — это то, ради чего всё затевалось.

    Поэтому берём перемешанный список и выдаём по одной. Кончился —
    перемешиваем заново, но так, чтобы первая не совпала с последней
    выданной.
    """

    def __init__(self, rng=None):
        self.rng = rng or random
        self._left: dict = {}
        self._last: dict = {}

    def next(self, pool: tuple) -> str:
        key = id(pool)
        left = self._left.get(key) or []

        if not left:
            left = list(pool)
            self.rng.shuffle(left)

            if len(left) > 1 and left[-1] == self._last.get(key):
                # Последняя в новой колоде совпала с только что выданной —
                # меняем её местами с соседней, иначе на стыке колод
                # получится повтор подряд.
                left[-1], left[-2] = left[-2], left[-1]

        phrase = left.pop()
        self._left[key] = left
        self._last[key] = phrase

        return phrase


def value_for(label: str, current: str = "", rng=None) -> str:
    """Что вписать в поле → строка.

    Своё значение продавца не выбрасываем: он его для чего-то ставил.
    Разнообразие тогда добавляется фразой следом, а не вместо.
    """
    pool = PROMO_PHRASES if is_promo(label) else PHRASES
    phrase = (rng.next(pool) if isinstance(rng, Rotation)
              else (rng or random).choice(pool))
    current = " ".join(str(current or "").split())

    if not current:
        return phrase

    if phrase in current:
        return current

    return f"{current} {phrase}"


def apply(fields, rng=None) -> list:
    """Разнообразить поля черновика. → названия тронутых.

    Правим на месте: поля — это тот самый список, который уйдёт на
    площадку, и подменять его целиком значило бы потерять всё остальное,
    что в нём уже заполнено.
    """
    touched = []

    for field in fields or []:
        label = str(field.get("label") or "")

        if not varied(label):
            continue

        field["value"] = value_for(label, field.get("value") or "", rng)
        touched.append(label)

    return touched
