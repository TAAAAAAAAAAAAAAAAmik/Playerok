#!/bin/sh
# Держать бота живым: запустить, если не запущен, и не запустить второго.
#
# Ставится в cron и зовётся раз в минуту. Первый вызов поднимает бота,
# следующие ничего не делают, пока он жив. Если бот упал или сервер
# перезагрузился — поднимет снова.
#
#   crontab -e
#   * * * * * /home/ВЫ/playerok/templates/autodelivery/run_bot.sh
#
# ДВА БОТА ОДНОВРЕМЕННО ЗАПУСКАТЬ НЕЛЬЗЯ. Telegram отдаёт каждое
# сообщение только одному опрашивающему: второй бот будет воровать ответы
# у первого, и оба будут выглядеть сломанными. Отсюда замок ниже.

set -eu

HERE=$(CD=$(dirname "$0"); cd "$CD" && pwd)
STATE="$HERE/state"
PIDFILE="$STATE/item_bot.pid"
LOG="$STATE/item_bot.log"

mkdir -p "$STATE"

# Уже жив? Тогда молча уходим. kill -0 не убивает, а только проверяет,
# что процесс с таким номером существует и наш.
if [ -f "$PIDFILE" ]; then
    PID=$(cat "$PIDFILE" 2>/dev/null || echo "")

    if [ -n "$PID" ] && kill -0 "$PID" 2>/dev/null; then
        exit 0
    fi
fi

# Вторая проверка — по самим процессам. Нужна, когда pid-файл потерян или
# затёрт, а бот жив: первой проверки тогда мало, и поднялся бы второй. Два
# бота воруют сообщения друг у друга, и выглядит это как сломанный бот, а
# не как две копии.
if command -v pgrep >/dev/null 2>&1; then
    ALIVE=$(pgrep -f "python3 -u item_bot.py" 2>/dev/null | head -1 || true)

    if [ -n "$ALIVE" ]; then
        echo "$ALIVE" > "$PIDFILE"
        exit 0
    fi
fi

# Журнал не должен съесть диск: у бота его немного, но он пишется годами.
if [ -f "$LOG" ] && [ "$(wc -c < "$LOG")" -gt 5000000 ]; then
    tail -c 1000000 "$LOG" > "$LOG.tmp" && mv "$LOG.tmp" "$LOG"
fi

cd "$HERE"

# nohup и & — чтобы бот пережил закрытие терминала: иначе он умирает
# вместе с оболочкой, из которой запущен.
nohup python3 -u item_bot.py >> "$LOG" 2>&1 &
echo $! > "$PIDFILE"

echo "$(date '+%Y-%m-%d %H:%M:%S') запущен, номер $(cat "$PIDFILE")" >> "$LOG"
