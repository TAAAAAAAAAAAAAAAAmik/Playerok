#!/bin/sh
# Держать бота живым: запустить, если не запущен, и не запустить второго.
#
# Запускает сторожа (keep_bot.sh), который держит бота живым и поднимает
# его после падения. Повторный вызов ничего не делает, пока сторож жив.
#
# После перезагрузки сервера позвать надо снова: где есть cron — строкой
# «* * * * * .../run_bot.sh», где нет — из ~/.profile, то есть при первом
# же входе на сервер.
#
# ДВА БОТА ОДНОВРЕМЕННО ЗАПУСКАТЬ НЕЛЬЗЯ. Telegram отдаёт каждое
# сообщение только одному опрашивающему: второй бот будет воровать ответы
# у первого, и оба будут выглядеть сломанными. Отсюда замок ниже.

set -eu

HERE=$(CD=$(dirname "$0"); cd "$CD" && pwd)
STATE="$HERE/state"

# Какого бота держать. По умолчанию тот, что создаёт товары; вторым
# аргументом можно поднять восстановление проданных:
#   ./run_bot.sh                  создание товаров
#   ./run_bot.sh restore_bot.py   восстановление проданных
WHAT=${1:-item_bot.py}
NAME=$(basename "$WHAT" .py)
PIDFILE="$STATE/$NAME.pid"
LOG="$STATE/$NAME.log"

mkdir -p "$STATE"

# Уже жив? Тогда молча уходим. kill -0 не убивает, а только проверяет,
# что процесс с таким номером существует и наш.
if [ -f "$PIDFILE" ]; then
    PID=$(cat "$PIDFILE" 2>/dev/null || echo "")

    if [ -n "$PID" ] && kill -0 "$PID" 2>/dev/null; then
        exit 0
    fi
fi

# Вторая проверка — по самим процессам. Нужна, когда pid-файл потерян или
# затёрт, а бот жив: первой проверки тогда мало, и поднялся бы второй. Два
# бота воруют сообщения друг у друга, и выглядит это как сломанный бот, а
# не как две копии.
if command -v pgrep >/dev/null 2>&1; then
    # Полный путь, а не просто имя: короткий шаблон совпадает с чем
    # угодно, где эта строка вообще встречается — вплоть до редактора,
    # открывшего этот файл. Один такой ложный «он уже запущен» и бот не
    # поднимется вовсе.
    ALIVE=$(pgrep -f "$HERE/keep_bot.sh $WHAT" 2>/dev/null | head -1 || true)

    if [ -n "$ALIVE" ]; then
        echo "$ALIVE" > "$PIDFILE"
        exit 0
    fi
fi

# Журнал не должен съесть диск: у бота его немного, но он пишется годами.
if [ -f "$LOG" ] && [ "$(wc -c < "$LOG")" -gt 5000000 ]; then
    tail -c 1000000 "$LOG" > "$LOG.tmp" && mv "$LOG.tmp" "$LOG"
fi

cd "$HERE"

# Запускаем не бота, а сторожа: он поднимет бота обратно, если тот
# упадёт. nohup и & — чтобы всё это пережило закрытие терминала, иначе
# умирает вместе с оболочкой, из которой запущено.
nohup "$HERE/keep_bot.sh" "$WHAT" >> "$LOG" 2>&1 &
echo $! > "$PIDFILE"

echo "$(date '+%Y-%m-%d %H:%M:%S') запущен, номер $(cat "$PIDFILE")" >> "$LOG"
