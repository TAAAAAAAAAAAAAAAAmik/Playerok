#!/bin/sh
# Обновиться и перезапустить всё, что должно работать — одной командой.
#
#     sh ~/playerok/templates/autodelivery/update.sh
#
# Ботов несколько, и это не прихоть: они делают разное и падают по
# отдельности.
#
#   item_bot      разговор в телеграме: создание товаров, настройки
#   delivery_bot  автовыдача: покупает код у поставщика и шлёт покупателю
#   notify_bot    уведомления: покупки, сообщения, проблемы, отзывы
#
# Раньше здесь запускался только item_bot, и выглядело это так, будто
# автовыдача сломана: на деле её никто не запускал. Поэтому теперь по
# умолчанию поднимается всё, для чего есть ключи.
#
# Одного бота можно назвать отдельно:
#     sh update.sh item_bot.py

set -eu

HERE=$(CD=$(dirname "$0"); cd "$CD" && pwd)

# Каким этот скрипт был до обновления — чтобы заметить, что он изменился.
WAS=$(cksum < "$HERE/update.sh" 2>/dev/null || echo нет)

python3 "$HERE/pull.py"

# Обновление могло принести новую версию этого же скрипта, а оболочка
# продолжает выполнять старую — ту, что уже прочитана. Из-за этого правка
# здесь вступала в силу только со ВТОРОГО запуска, и выглядело это как
# «обновился, а всё по-старому»: код свежий, а поднимается по-прежнему
# один item_bot.
#
# Поэтому: файл изменился — выполняем себя новым. Метка бережёт от круга,
# если запись почему-то не остановится.
NOW=$(cksum < "$HERE/update.sh" 2>/dev/null || echo нет)

if [ "${UPDATE_RESTARTED:-}" != "1" ] && [ "$NOW" != "$WAS" ]; then
    echo "Скрипт обновления сам обновился — перечитываю его."
    UPDATE_RESTARTED=1 exec sh "$HERE/update.sh" "$@"
fi

restart() {
    # Остановка и запуск раздельно: если бот не был запущен, останавливать
    # нечего, и это не повод не запускать.
    sh "$HERE/stop_bot.sh" "$1" || true
    sh "$HERE/run_bot.sh" "$1"
}

if [ $# -gt 0 ]; then
    restart "$1"
    echo
    sh "$HERE/status_bot.sh"
    exit 0
fi

restart item_bot.py
restart notify_bot.py

# Выдача — только если есть чем покупать. Без ключа поставщика она
# падает сразу, и сторож поднимал бы её по кругу, засоряя журнал.
if grep -qs '^APPROUTE_KEY=..*' "$HERE/.env"; then
    restart delivery_bot.py
else
    echo
    echo "Автовыдачу не поднимаю: в .env нет APPROUTE_KEY."
    echo "Это ключ кабинета AppRoute, которым покупаются коды."
fi

echo
sh "$HERE/status_bot.sh"
