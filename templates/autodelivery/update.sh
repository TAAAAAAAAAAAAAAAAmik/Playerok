#!/bin/sh
# Обновиться и перезапуститься — одной командой, из любой папки.
#
#     sh ~/playerok/templates/autodelivery/update.sh
#
# Делает ровно то, что делалось руками в три шага: скачивает свежий код,
# останавливает бота и поднимает его заново под сторожем. Три шага легко
# перепутать местами или промахнуться путём, а промах виден не сразу:
# бот работает, но по старому коду, и это выглядит как «не починилось».
#
# Вторым аргументом можно назвать другого бота:
#     sh update.sh restore_bot.py

set -eu

HERE=$(CD=$(dirname "$0"); cd "$CD" && pwd)
WHAT=${1:-item_bot.py}

python3 "$HERE/pull.py"

# Остановка и запуск раздельно: если бот не был запущен, останавливать
# нечего, и это не повод не запускать.
sh "$HERE/stop_bot.sh" "$WHAT" || true
sh "$HERE/run_bot.sh" "$WHAT"

echo
sh "$HERE/status_bot.sh"
